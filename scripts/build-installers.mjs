import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const files = [
  'AGENTS.md', 'PROJECT.md', '.pi/settings.json', '.pi/APPEND_SYSTEM.md', '.pi/STATE.example.md',
  '.pi/prompts/project-start.md', '.pi/prompts/project-save.md', '.pi/prompts/project-resume.md', '.pi/prompts/project-check.md',
  'config/pi/models.r9700.json', 'scripts/configure-models.mjs', 'scripts/configure-models.sh', 'scripts/configure-models.bat',
  'docs/DECISIONS.md', '.editorconfig', '.gitattributes', '.github/PULL_REQUEST_TEMPLATE.md',
];
const encoded = Object.fromEntries(files.map(file => [file, fs.readFileSync(path.join(root, file)).toString('base64')]));
const core = fs.readFileSync(path.join(root, 'scripts/project-installer-core.mjs'), 'utf8').replaceAll('\r\n', '\n');
const bundle = {files: encoded};
const fingerprint = createHash('sha256').update(core).update(JSON.stringify(bundle)).digest('hex');
const program = `// Generated by build-installers.mjs; edit source files, then rebuild.\n// Bundle SHA256: ${fingerprint}\n${core}\nconst BUNDLE = ${JSON.stringify(bundle)};\ntry { installProject(BUNDLE); } catch (error) { console.error(error instanceof Error ? error.message : 'Project installation failed.'); process.exitCode = 1; }\n`;
const outputs = {
  'install-project.mjs': program,
  'install-project.sh': `#!/usr/bin/env bash\nset -euo pipefail\ncommand -v node >/dev/null 2>&1 || { printf '%s\\n' 'Node.js 22.19+ is required.' >&2; exit 1; }\nnode --input-type=module - "$@" <<'PI_PROJECT_NODE_EOF'\n${program}PI_PROJECT_NODE_EOF\n`,
  'install-project.bat': `@echo off\r\nsetlocal\r\nwhere node >nul 2>nul\r\nif errorlevel 1 (\r\n  echo Node.js 22.19+ is required. 1>&2\r\n  exit /b 1\r\n)\r\nnode -e "const s=require('fs').readFileSync(process.argv[1],'utf8'); import('data:text/javascript;base64,'+s.split(':::PI_INIT_PAYLOAD:::').pop().trim())" "%~f0" %*\r\nexit /b %errorlevel%\r\n:::PI_INIT_PAYLOAD:::\r\n${Buffer.from(program).toString('base64')}\r\n`,
};
for (const [name, text] of Object.entries(outputs)) {
  const output = path.join(root, 'scripts', name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) {
      console.error(`Generated installer is stale: ${name}`);
      process.exitCode = 1;
    }
  } else fs.writeFileSync(output, text, {mode: name.endsWith('.sh') ? 0o755 : 0o644});
}
console.log(`Installer bundle: ${files.length} files; ${fingerprint}`);
